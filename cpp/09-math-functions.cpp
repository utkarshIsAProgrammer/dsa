#include <cmath>
#include <iostream>
using namespace std;

int main() {
  double a = 6;
  double b = 9;

  // max number
  cout << max(a, b) << endl;

  // min number
  cout << min(a, b) << endl;

  // power of a number
  cout << pow(a, 2) << endl;

  // square root
  cout << sqrt(9) << endl;

  // absolute value
  cout << abs(-3) << endl;

  // round to nearest integer
  cout << round(3.3) << endl;

  // round up
  cout << ceil(3.2) << endl;

  // round down
  cout << floor(3.9) << endl;

  return 0;
}
